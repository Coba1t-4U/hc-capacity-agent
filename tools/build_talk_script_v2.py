    rs.font.name = FONT
    rs.font.size = Pt(9)
    rs.font.color.rgb = GREY

    total = 0
    for page, title, tcode, cue, text in PAGES:
        h = doc.add_paragraph()
        h.paragraph_format.space_before = Pt(10)
        hr = h.add_run(f"第 {page} 页　{title}　　{tcode}")
        hr.font.name = FONT
        hr.font.size = Pt(12)
        hr.font.bold = True
        hr.font.color.rgb = BLUE

        c = doc.add_paragraph()
        c.paragraph_format.space_after = Pt(3)
        cr = c.add_run(f"【画面】{cue}")
        cr.font.name = FONT
        cr.font.size = Pt(9)
        cr.font.color.rgb = GREY

        b = doc.add_paragraph()
        b.paragraph_format.line_spacing = 1.45
        br = b.add_run(text)
        br.font.name = FONT
        br.font.size = Pt(11)
        total += len(text)

    tail = doc.add_paragraph()
    tail.paragraph_format.space_before = Pt(14)
    tr = tail.add_run(
        f"口播合计约 {total} 字，按 220 字/分钟约 {total / 220:.1f} 分钟；"
        f"含翻页与停顿，实讲约 15 分钟。若需压缩到 12 分钟，删第 3、10、14 页各一段。")
