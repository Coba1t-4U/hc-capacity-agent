def build_ppt() -> Path:
    prs = Presentation()
    prs.slide_width = PCm(PAGE_W)
    prs.slide_height = PCm(PAGE_H)
    blank = prs.slide_layouts[6]

    def tb(slide, x, y, w, h, text, size, bold=False, color=DARK,
           align=PP_ALIGN.LEFT):
        box = slide.shapes.add_textbox(PCm(x), PCm(y), PCm(w), PCm(h))
        tf = box.text_frame
        tf.word_wrap = True
        p = tf.paragraphs[0]
        p.alignment = align
        r = p.add_run()
        r.text = text
        r.font.name = FONT
        r.font.size = PPt(size)
        r.font.bold = bold
        r.font.color.rgb = color
        return box

    total = len(SLIDES)
    for idx, (title, bullets, _note) in enumerate(SLIDES):
        s = prs.slides.add_slide(blank)
        # 顶部色带
        bar = s.shapes.add_shape(1, PCm(0), PCm(0), PCm(PAGE_W), PCm(0.28))
        bar.fill.solid()
        bar.fill.fore_color.rgb = BLUE
        bar.line.fill.background()

        if idx == 0:
            tb(s, 2.2, 5.2, 29, 2.4, title, 40, True, BLUE)
            tb(s, 2.2, 8.0, 29, 1.2, bullets[0], 24, False, DARK)
            tb(s, 2.2, 12.6, 29, 1.0, bullets[1], 18, False, GREY)
            tb(s, 2.2, 14.4, 29, 1.0, bullets[2], 16, False, GREY)
        else:
            tb(s, 1.6, 0.9, 30.5, 1.6, title, 26, True, BLUE)
            line = s.shapes.add_shape(1, PCm(1.6), PCm(2.55), PCm(3.2), PCm(0.10))
            line.fill.solid()
            line.fill.fore_color.rgb = BLUE
            line.line.fill.background()
            y = 3.2
            for b in bullets:
                size = 20 if len(b) <= 34 else (18 if len(b) <= 46 else 16)
                tb(s, 1.8, y, 30.2, 1.5, b, size, False, DARK)
                y += 1.55 if size >= 18 else 1.35
        # 页码
        tb(s, PAGE_W - 4.2, PAGE_H - 1.4, 3.4, 0.8, f"{idx + 1} / {total}", 12,
           False, GREY, PP_ALIGN.RIGHT)
        # 备注页 = 演讲稿
        s.notes_slide.notes_text_frame.text = _note

    prs.save(str(OUT_PPT))
    return OUT_PPT


def build_doc() -> Path:
    doc = Document()
    doc.sections[0].left_margin = doc.sections[0].right_margin = Cm(2.2)
    h = doc.add_paragraph()
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = h.add_run("配网承载力智能体 · 15 分钟汇报讲稿")
    r.font.name = FONT
    r.font.size = Pt(17)
    r.font.bold = True
    r.font.color.rgb = RGBColor(0x01, 0x4C, 0x83)
    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    rs = sub.add_run(f"共 {len(SLIDES)} 页　|　每页对应一段口播")
    rs.font.name = FONT
    rs.font.size = Pt(9)
    rs.font.color.rgb = RGBColor(0x5A, 0x62, 0x6A)

    total_chars = 0
    for i, (title, bullets, note) in enumerate(SLIDES, 1):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(10)
        rr = p.add_run(f"第 {i} 页　{title}")
        rr.font.name = FONT
        rr.font.size = Pt(12)
        rr.font.bold = True
        rr.font.color.rgb = RGBColor(0x01, 0x4C, 0x83)
        for b in bullets:
            bp = doc.add_paragraph()
            bp.paragraph_format.left_indent = Cm(0.5)
            bp.paragraph_format.space_after = Pt(2)
            br = bp.add_run("· " + b)
            br.font.name = FONT
            br.font.size = Pt(9)
            br.font.color.rgb = RGBColor(0x5A, 0x62, 0x6A)
        body = doc.add_paragraph()
        body.paragraph_format.space_before = Pt(4)
        body.paragraph_format.line_spacing = 1.4
        bb = body.add_run(note)
        bb.font.name = FONT
        bb.font.size = Pt(10.5)
        total_chars += len(note)
    tail = doc.add_paragraph()
    tail.paragraph_format.space_before = Pt(14)
    rt = tail.add_run(f"口播合计约 {total_chars} 字，按 230 字/分钟约 {total_chars/230:.1f} 分钟。")
    rt.font.name = FONT
    rt.font.size = Pt(9)
    rt.font.color.rgb = RGBColor(0x5A, 0x62, 0x6A)
    doc.save(str(OUT_DOC))
    return OUT_DOC, total_chars


if __name__ == "__main__":
    ppt = build_ppt()
